// Writes screens/<id>.ts and web/src/game/layout_<id>.ts from measured items.
import fs from "node:fs";
import path from "node:path";

const r1 = (n) => Math.round(n * 10) / 10;

export function emitScreen(here, id, def, m) {
  const items = m.items.filter((i) => !i.missing);
  const elements = items.map((i) => {
    const e = { name: i.name, kind: i.kind, ...i.def };
    if (i.text) e.text = i.text;
    return e;
  });
  const bgCss = def.bgCss === "EMAIL_BG" ? m.bgCss : def.bgCss;
  const screen = { id, label: def.label, ...(def.bg ? { bg: def.bg } : {}), ...(bgCss ? { bgCss } : {}), elements };
  const sconst = id;
  fs.writeFileSync(
    path.join(here, "screens", `${id}.ts`),
    `import type { ScreenDef } from "./types";\n\n// Generated by extract.mjs from the running game at 720x1280 (lang ko). Elements are in stacking order.\n// Coordinates are in web/src/game/layout_${id}.ts. Hand edits are fine; re-running extract.mjs overwrites this file.\nexport const ${sconst}: ScreenDef = ${JSON.stringify(screen, null, 2)};\n`,
  );
  const lines = items.map((i) => {
    const font = i.text && i.font ? `, font: ${r1(i.font)}` : "";
    const note = i.def.note ? ` // ${i.def.note}` : "";
    return `  ${i.name}: { x: ${r1(i.x)}, y: ${r1(i.y)}, w: ${r1(i.w)}, h: ${r1(i.h)}${font} },${note}`;
  });
  const file = path.resolve(here, "..", "..", "web", "src", "game", `layout_${id}.ts`);
  fs.writeFileSync(
    file,
    `// ${def.label} layout (coordinates = the 720x1280 game frame 1:1; x,y = element CENTER; w,h = displayed size; font = px).\n// Measured from the running game (DOM getBoundingClientRect). NOT read by game code yet: the game still uses its own CSS/Phaser\n// values; this file only holds the same numbers for the layout editor (tools/layout-editor, apply_layout.mjs ${id}).\nexport const ${id.toUpperCase()}_LAYOUT = {\n${lines.join("\n")}\n} as const;\n`,
  );
}
