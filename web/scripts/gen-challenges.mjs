// Bundles content/challenges/*.json into src/lib/challenges.generated.ts so Workers (no disk) can read them.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "content/challenges";
const days = readdirSync(dir).filter((n) => /^\d{4}-\d{2}-\d{2}\.json$/.test(n)).sort();
const body = days.map((n) => JSON.stringify(JSON.parse(readFileSync(`${dir}/${n}`, "utf8")))).join(",\n  ");
writeFileSync("src/lib/challenges.generated.ts", `// GENERATED by scripts/gen-challenges.mjs - do not edit.\nexport const bundledChallenges: unknown[] = [\n  ${body},\n];\n`);
console.log(`bundled ${days.length} day files`);
